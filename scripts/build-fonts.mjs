// Build the self-hosted body fonts.
//
//   - Latin & digits : Inter (variable, wght 100-900)
//   - CJK            : Noto Sans SC (variable, wght 100-900)
//
// Noto Sans SC is the Google-side release of Source Han Sans
// (思源黑体), so the Chinese half of the stack is already the face
// the design calls for; Inter is layered IN FRONT of it and only
// owns Latin letters and digits. CSS font matching is per-glyph,
// so each script lands on its own face from one --font-sans stack.
//
// Both come from @fontsource-variable packages that ship the font
// pre-sliced into woff2 chunks behind unicode-range declarations —
// a visitor only downloads the slices their text actually touches.
//
// What this script does, per font:
//   1. copies every woff2 chunk into static/fonts/<dir>/ (committed,
//      so deploys never need the devDependency),
//   2. emits @font-face rules into styles/_fonts.scss, family
//      renamed and urls rewritten to the shipped path.
//
// Run manually via `npm run fonts`; rerun only when bumping a
// fontsource package version.
import { mkdirSync, cpSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { join } from "node:path";

const FONTS = [
    {
        pkg: "@fontsource-variable/inter",
        family: "Inter",
        css: "wght.css",
        outDir: join("static", "fonts", "inter"),
    },
    {
        pkg: "@fontsource-variable/noto-sans-sc",
        family: "Noto Sans SC",
        css: "wght.css",
        outDir: join("static", "fonts", "noto-sans-sc"),
    },
];

const outScss = join("styles", "_fonts.scss");

let blocks = [];
let total = 0;
for (const font of FONTS) {
    const srcDir = join("node_modules", font.pkg);
    const css = readFileSync(join(srcDir, font.css), "utf8");

    // Copy only the woff2 chunks this CSS actually references —
    // fontsource ships extra axes/styles (opsz, italic) we don't use.
    rmSync(font.outDir, { recursive: true, force: true });
    mkdirSync(font.outDir, { recursive: true });
    const urlPrefix = `/static/fonts/${font.pkg.split("/").pop()}`;
    const referenced = [...css.matchAll(/\.\/files\/([^)]+\.woff2)/g)].map((m) => m[1]);
    for (const name of referenced) {
        cpSync(join(srcDir, "files", name), join(font.outDir, name));
    }

    // Rewrite the shipped CSS: rename the family, point src at the
    // committed path, normalize the format hint.
    const rewritten = css
        .replace(new RegExp(`'${font.family} Variable'`, "g"), `'${font.family}'`)
        .replace(/url\(\.\/files\/([^)]+\.woff2)\)/g, `url("${urlPrefix}/$1")`)
        .replace(/format\('woff2-variations'\)/g, `format("woff2-variations")`);

    blocks.push(`/* ---- ${font.family} (${font.pkg}) ---- */\n\n${rewritten}`);
    total += referenced.length;
    console.log(`fonts: ${font.family}: ${referenced.length} chunks -> ${font.outDir}`);
}

writeFileSync(
    outScss,
    `/* GENERATED by scripts/build-fonts.mjs — do not edit.\n` +
        `   Sources: ${FONTS.map((f) => f.pkg).join(", ")} (variable, wght 100-900),\n` +
        `   sliced per unicode-range. Regenerate with \`npm run fonts\`. */\n\n` +
        blocks.join("\n\n") +
        "\n"
);

console.log(`fonts: ${total} chunks total, @font-face set -> ${outScss}`);
